#!/usr/bin/env node

/**
 * Generates a TypeScript manifest enumerating matcap and IBL assets.
 * Run with `node scripts/generate-asset-manifest.js`.
 */

const fs = require('fs');
const path = require('path');

const repoRoot = path.resolve(__dirname, '..');
const matcapDir = path.join(repoRoot, 'assets', 'textures', 'matcaps');
const iblDir = path.join(repoRoot, 'assets', 'textures', 'ibl');
const manifestDir = path.join(repoRoot, 'src', 'lucid3d', 'assets');
const manifestPath = path.join(manifestDir, 'asset-manifest.ts');

function ensureDir(directory) {
  if (!fs.existsSync(directory)) {
    fs.mkdirSync(directory, { recursive: true });
  }
}

function readDirSafe(directory) {
  try {
    return fs.readdirSync(directory);
  } catch (err) {
    console.error(`Failed to read directory ${directory}:`, err);
    process.exitCode = 1;
    return [];
  }
}

function listMatcaps() {
  return readDirSafe(matcapDir)
    .filter((entry) => entry.toLowerCase().endsWith('.png'))
    .sort((a, b) => a.localeCompare(b))
    .map((filename) => ({
      name: filename.replace(/\.(png)$/i, ''),
      file: `assets/textures/matcaps/${filename}`,
    }));
}

function toLabel(name) {
  return name
    .replace(/[_\-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/\b\w/g, (c) => c.toUpperCase());
}

function listIblEnvironments() {
  const entries = readDirSafe(iblDir)
    .filter((entry) => fs.statSync(path.join(iblDir, entry)).isDirectory())
    .sort((a, b) => a.localeCompare(b));

  return entries.map((folder) => {
    const fullFolder = path.join(iblDir, folder);
    const files = readDirSafe(fullFolder);
    const hdr = files.find((file) => file.toLowerCase().endsWith('.hdr'));
    if (!hdr) {
      console.warn(`Skipping ${folder}: no HDR file found`);
      return null;
    }
    const preview = files.find((file) => /\.(png|jpg|jpeg|webp)$/i.test(file) && file !== hdr);
    return {
      name: folder,
      label: toLabel(folder),
      hdr: `assets/textures/ibl/${folder}/${hdr}`,
      preview: preview ? `assets/textures/ibl/${folder}/${preview}` : null,
    };
  }).filter(Boolean);
}

function writeManifest(matcaps, ibls) {
  const header = `// AUTO-GENERATED FILE — DO NOT EDIT
// Generated by scripts/generate-asset-manifest.js

export type MatcapAsset = {
  name: string;
  url: string;
};

export type IblEnvironmentAsset = {
  name: string;
  label: string;
  hdrUrl: string;
  previewUrl?: string;
};

export const MATCAP_ASSETS: MatcapAsset[] = [
${matcaps.map((m) => `  { name: ${JSON.stringify(m.name)}, url: ${JSON.stringify(m.file)} },`).join('\n')}
];

export const IBL_ENVIRONMENT_ASSETS: IblEnvironmentAsset[] = [
${ibls.map((ibl) => `  { name: ${JSON.stringify(ibl.name)}, label: ${JSON.stringify(ibl.label)}, hdrUrl: ${JSON.stringify(ibl.hdr)},${ibl.preview ? ` previewUrl: ${JSON.stringify(ibl.preview)},` : ''} },`).join('\n')}
];
`;

  ensureDir(manifestDir);
  fs.writeFileSync(manifestPath, `${header}`, 'utf8');
  console.log(`Wrote ${manifestPath}`);
}

function main() {
  ensureDir(matcapDir);
  ensureDir(iblDir);
  const matcaps = listMatcaps();
  const ibls = listIblEnvironments();
  writeManifest(matcaps, ibls);
}

main();
